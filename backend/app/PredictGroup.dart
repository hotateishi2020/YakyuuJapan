  static Future<Map<String, dynamic>> _prepareTitles(Connection conn, List<Map<String, dynamic>> titles) async {
    final prepared = <Map<String, dynamic>>[];
    final seen = <String>{};
    for (final row in titles) {
      final title = '${row['txt_title'] ?? row['title'] ?? ''}'.trim();
      if (title.isEmpty || !seen.add(title)) continue;
      if (title.length > 80) return {'error': 'タイトルが長すぎます'};
      if (specialTitles.contains(title)) {
        prepared.add({'id_stats': null, 'txt_title': title});
        continue;
      }
      var statsId = _asInt(row['id_stats']);
      if (statsId <= 0) statsId = await _statsIdOf(conn, title) ?? 0;
      if (statsId <= 0) return {'error': '$title は成績タイトルにありません'};
      prepared.add({'id_stats': statsId, 'txt_title': title});
    }
    return {'titles': prepared};
  }

  static Future<Map<String, dynamic>> _preparePicks(
    Connection conn,
    int settingId,
    List<Map<String, dynamic>> picks,
    int actorId,
  ) async {
    final yearRows = await conn.execute(
      '''
      SELECT int_year FROM t_predict_setting
      WHERE id = \$1 AND COALESCE(flg_delete, FALSE) = FALSE
      ''',
      parameters: [settingId],
    );
    if (yearRows.isEmpty) return {'error': '予想設定を保存できませんでした'};
    final year = _asInt(yearRows.first.toColumnMap()['int_year']);
    if (year <= 0) return {'error': '予想設定を保存できませんでした'};
    final prepared = <Map<String, dynamic>>[];
    for (final row in picks) {
      final name = '${row['name'] ?? ''}'.trim();
      if (name.isEmpty) continue;
      final title = '${row['txt_title'] ?? ''}'.trim();
      if (specialTitles.contains(title)) continue;
      final userId = _asInt(row['id_user']);
      final leagueId = _asInt(row['id_league']);
      final sawamura = title == '沢村賞';
      if (userId != actorId) return {'error': '自分の予想だけ修正できます'};
      if (userId <= 0 || (sawamura ? leagueId != 0 : leagueId != 1 && leagueId != 2)) {
        return {'error': '予想選手のリーグまたはユーザーが不正です'};
      }
      var statsId = _asInt(row['id_stats']);
      if (statsId <= 0) statsId = await _statsIdOf(conn, title) ?? 0;
      if (statsId <= 0) return {'error': '$title は成績タイトルにありません'};
      final player = await _findPlayer(conn, name, leagueId, year);
      if (player == null) {
        final leagueName = sawamura
            ? 'NPB'
            : leagueId == 1
                ? 'セ・リーグ'
                : 'パ・リーグ';
        return {'error': '$name（$leagueName）が見つかりません'};
      }
      prepared.add({
        'id_user': userId,
        'id_league': leagueId,
        'id_stats': statsId,
        'id_player': player.id,
        'id_team': player.teamId,
      });
    }
    return {'picks': prepared};
  }

