  static Future<String?> _waiverPickError(
    Connection conn, {
    required int settingId,
    required int year,
    required int actorId,
    required Set<int> members,
    required List<Map<String, dynamic>> nextPicks,
  }) async {
    final titleRows = await conn.execute(
      '''
      SELECT txt_title FROM t_predict_setting_details
      WHERE id_predict_setting = \$1 AND COALESCE(flg_delete, FALSE) = FALSE
      ''',
      parameters: [settingId],
    );
    var expected = 0;
    for (final row in titleRows) {
      final title = '${row.toColumnMap()['txt_title'] ?? ''}'.trim();
      if (title.isEmpty || specialTitles.contains(title)) continue;
      expected += (title == '沢村賞' ? 1 : 2) * members.length;
    }
    final existingRows = await conn.execute(
      '''
      SELECT id_user, id_league, id_stats, id_player
      FROM t_predict_player
      WHERE id_predict_setting = \$1 AND COALESCE(flg_delete, FALSE) = FALSE
      ''',
      parameters: [settingId],
    );
    final counts = <int, int>{for (final id in members) id: 0};
    final mine = <String>{};
    for (final row in existingRows) {
      final map = row.toColumnMap();
      final user = _asInt(map['id_user']);
      if (!counts.containsKey(user)) continue;
      counts[user] = (counts[user] ?? 0) + 1;
      if (user == actorId) {
        mine.add('${_asInt(map['id_league'])}|${_asInt(map['id_stats'])}|${_asInt(map['id_player'])}');
      }
    }
    final filled = counts.values.fold<int>(0, (sum, count) => sum + count);
    if (expected <= 0 || filled >= expected) return null;
    final next = <String>{
      for (final pick in nextPicks) '${_asInt(pick['id_league'])}|${_asInt(pick['id_stats'])}|${_asInt(pick['id_player'])}',
    };
    if (next.length == mine.length && next.containsAll(mine)) return null;
    final hits = await _previousHits(conn, year - 1, members, settingId);
    final order = members.toList()
      ..sort((a, b) {
        final rank = (hits[a] ?? 0).compareTo(hits[b] ?? 0);
        if (rank != 0) return rank;
        return a.compareTo(b);
      });
    if (order.isEmpty) return null;
    var least = counts[order.first] ?? 0;
    for (final id in order) {
      final count = counts[id] ?? 0;
      if (count < least) least = count;
    }
    var turn = order.first;
    for (final id in order) {
      if ((counts[id] ?? 0) == least) {
        turn = id;
        break;
      }
    }
    if (actorId != turn) return '今はあなたの選択順ではありません';
    final added = next.difference(mine);
    final removed = mine.difference(next);
    if (removed.isNotEmpty || added.length != 1) {
      return 'ウェーバー方式では、空いているタイトルを1つだけ選べます';
    }
    return null;
  }

  static Future<Map<int, int>> _previousHits(Connection conn, int year, Set<int> members, int settingId) async {
    final hits = <int, int>{for (final id in members) id: 0};
    if (year <= 0) return hits;
    final players = await conn.execute(
      '''
      SELECT DISTINCT p.id_user, p.id_league, p.id_stats
      FROM t_predict_player p
      WHERE p.year = \$1
        AND EXISTS (
          SELECT 1 FROM t_predict_setting prior
          JOIN t_predict_setting current ON current.id_predict_group = prior.id_predict_group
          WHERE current.id = \$2 AND prior.id = p.id_predict_setting
            AND COALESCE(prior.flg_delete, FALSE) = FALSE
        )
        AND COALESCE(p.flg_delete, FALSE) = FALSE
        AND EXISTS (
          SELECT 1 FROM t_stats_player s
          WHERE s.int_year = p.year
            AND s.id_league = p.id_league
            AND s.id_stats = p.id_stats
            AND s.id_player = p.id_player
            AND s.int_rank = 1
            AND COALESCE(s.flg_delete, FALSE) = FALSE
        )
      ''',
      parameters: [year, settingId],
    );
    for (final row in players) {
      final user = _asInt(row.toColumnMap()['id_user']);
      if (!hits.containsKey(user)) continue;
      hits[user] = (hits[user] ?? 0) + 1;
    }
    final teams = await conn.execute(
      '''
      SELECT p.id_user
      FROM t_predict_team p
      WHERE p.int_year = \$1
        AND EXISTS (
          SELECT 1 FROM t_predict_setting prior
          JOIN t_predict_setting current ON current.id_predict_group = prior.id_predict_group
          WHERE current.id = \$2 AND prior.id = p.id_predict_setting
            AND COALESCE(prior.flg_delete, FALSE) = FALSE
        )
        AND EXISTS (
          SELECT 1 FROM t_stats_team st
          WHERE st.year = p.int_year
            AND st.id_team = p.id_team
            AND st.int_rank = p.int_rank
            AND st.crtat = (
              SELECT MAX(st2.crtat) FROM t_stats_team st2
              WHERE st2.id_team = st.id_team AND st2.year = st.year
            )
        )
      ''',
      parameters: [year, settingId],
    );
    for (final row in teams) {
      final user = _asInt(row.toColumnMap()['id_user']);
      if (!hits.containsKey(user)) continue;
      hits[user] = (hits[user] ?? 0) + 1;
    }
    final champions = await conn.execute(
      '''
      SELECT p.id_user
      FROM t_predict_team p
      JOIN t_japan_champion j
        ON j.int_year = p.int_year
       AND j.id_team = p.id_team
       AND COALESCE(j.flg_delete, FALSE) = FALSE
      WHERE p.int_year = \$1
        AND EXISTS (
          SELECT 1 FROM t_predict_setting prior
          JOIN t_predict_setting current ON current.id_predict_group = prior.id_predict_group
          WHERE current.id = \$2 AND prior.id = p.id_predict_setting
            AND COALESCE(prior.flg_delete, FALSE) = FALSE
        )
        AND p.flg_champion = TRUE
      ''',
      parameters: [year, settingId],
    );
    for (final row in champions) {
      final user = _asInt(row.toColumnMap()['id_user']);
      if (!hits.containsKey(user)) continue;
      hits[user] = (hits[user] ?? 0) + 1;
    }
    return hits;
  }

  static Future<Map<String, dynamic>> _prepareRanks(
    Connection conn,
    List<Map<String, dynamic>> ranks,
    List<Map<String, dynamic>> champions,
    int actorId,
  ) async {
    final prepared = <Map<String, dynamic>>[];
    final teamsByUser = <int, Set<int>>{};
    for (final row in ranks) {
      final name = '${row['name'] ?? ''}'.trim();
      if (name.isEmpty) continue;
      final userId = _asInt(row['id_user']);
      final leagueId = _asInt(row['id_league']);
      final rank = _asInt(row['rank']);
      if (userId != actorId) return {'error': '自分の予想だけ修正できます'};
      if (userId <= 0 || (leagueId != 1 && leagueId != 2) || rank < 1 || rank > 6) {
        return {'error': 'チーム順位の指定が不正です'};
      }
      final teamId = await _findTeam(conn, name, leagueId);
      if (teamId == null) {
        final leagueName = leagueId == 1 ? 'セ・リーグ' : 'パ・リーグ';
        return {'error': '$name（$leagueName）のチームが見つかりません'};
      }
      teamsByUser.putIfAbsent(userId, () => {}).add(teamId);
      prepared.add({
        'id_user': userId,
        'id_league': leagueId,
        'rank': rank,
        'id_team': teamId,
        'champion': false,
      });
    }
    for (final row in champions) {
      final name = '${row['name'] ?? ''}'.trim();
      if (name.isEmpty) continue;
      final userId = _asInt(row['id_user']);
      if (userId != actorId) return {'error': '自分の予想だけ修正できます'};
      final teamId = await _findTeam(conn, name, 0);
      if (teamId == null) return {'error': '日本一の $name が見つかりません'};
      if (!(teamsByUser[userId]?.contains(teamId) ?? false)) {
        return {'error': '日本一の $name が順位予想にありません'};
      }
      for (final rank in prepared) {
        if (rank['id_user'] == userId && rank['id_team'] == teamId) {
          rank['champion'] = true;
        }
      }
    }
    return {'ranks': prepared};
  }

