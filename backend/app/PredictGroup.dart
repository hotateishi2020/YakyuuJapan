  static void _ensureAwardRows(
    Map<String, Map<String, dynamic>> byTitle,
    List<Map<String, dynamic>> titleRows,
    List<Map<String, dynamic>> leaders,
    int? year,
  ) {
    for (final row in titleRows) {
      final title = '${row['txt_title'] ?? ''}'.trim();
      final statsId = row['id_stats'] == null ? 0 : _asInt(row['id_stats']);
      final slots = title == 'MVP'
          ? const [(id: 1, name: 'セ・リーグ'), (id: 2, name: 'パ・リーグ')]
          : title == '沢村賞'
              ? const [(id: 0, name: '')]
              : const <({int id, String name})>[];
      for (final league in slots) {
        byTitle.putIfAbsent('${league.id}|$statsId', () {
          return _awardBucket(
            leagueId: league.id,
            leagueName: league.name,
            statsId: statsId,
            title: title,
            pitcher: title == '沢村賞',
            leaders: leaders,
            year: year,
          );
        });
      }
    }
  }

  static Map<String, dynamic> _awardBucket({
    required int leagueId,
    required String leagueName,
    required int statsId,
    required String title,
    required bool pitcher,
    required List<Map<String, dynamic>> leaders,
    required int? year,
  }) {
    final names = <String>[];
    final backs = <String>[];
    final fonts = <String>[];
    final matched = <Map<String, dynamic>>[];
    for (final leader in leaders) {
      if (_asInt(leader['int_year']) != year) continue;
      if (_asInt(leader['id_league']) != leagueId || _asInt(leader['id_stats']) != statsId) {
        continue;
      }
      final name = '${leader['player_name'] ?? ''}'.trim();
      if (name.isNotEmpty && !names.contains(name)) {
        names.add(name);
        backs.add('${leader['color_back'] ?? ''}'.trim());
        fonts.add('${leader['color_font'] ?? ''}'.trim());
      }
      matched.add(leader);
    }
    return {
      'league': leagueName,
      'id_league': leagueId,
      'id_stats': statsId,
      'title': title,
      'pitcher': pitcher,
      'current': names.join('、'),
          'current_players': [for (final name in names) matched.firstWhere((p) => '${p['player_name'] ?? ''}'.trim() == name)],
      'color_backs': backs,
      'color_fonts': fonts,
      'color_back': names.length > 1 ? 'white' : _singlePaint(matched, 'color_back'),
      'color_font': names.length > 1 ? 'black' : _singlePaint(matched, 'color_font'),
      'picks': <Map<String, dynamic>>[],
    };
  }

  static String _singlePaint(List<Map<String, dynamic>> rows, String key) {
    final values = <String>{};
    for (final row in rows) {
      final value = '${row[key] ?? ''}'.trim();
      if (value.isNotEmpty) values.add(value);
    }
    return values.length == 1 ? values.first : '';
  }

  static Map<String, dynamic> _waiverMap({
    required String codeSelect,
    required int? year,
    required List<Map<String, dynamic>> members,
    required List<Map<String, dynamic>> titleRows,
    required List<Map<String, dynamic>> playerRows,
    required Map<String, int> hits,
    Map<String, dynamic>? lastPick,
  }) {
    final order = [for (final member in members) _asInt(member['id_user'])]..sort((a, b) {
        final rank = (hits['${(year ?? 0) - 1}|$a'] ?? 0).compareTo(hits['${(year ?? 0) - 1}|$b'] ?? 0);
        if (rank != 0) return rank;
        return a.compareTo(b);
      });
    final counts = <int, int>{for (final id in order) id: 0};
    for (final row in playerRows) {
      final user = _asInt(row['id_user']);
      if (!counts.containsKey(user)) continue;
      counts[user] = (counts[user] ?? 0) + 1;
    }
    var expected = 0;
    for (final row in titleRows) {
      final title = '${row['txt_title'] ?? ''}'.trim();
      if (title.isEmpty || specialTitles.contains(title)) continue;
      expected += (title == '沢村賞' ? 1 : 2) * order.length;
    }
    final filled = counts.values.fold<int>(0, (sum, count) => sum + count);
    final active = codeSelect == 'WAIVER' && year != null && expected > 0 && filled < expected;
    var turn = 0;
    if (order.isNotEmpty) {
      var least = counts[order.first] ?? 0;
      for (final id in order) {
        final count = counts[id] ?? 0;
        if (count < least) least = count;
      }
      for (final id in order) {
        if ((counts[id] ?? 0) == least) {
          turn = id;
          break;
        }
      }
    }
    String nameOf(int id) {
      for (final member in members) {
        if (_asInt(member['id_user']) == id) {
          return '${member['name_last'] ?? ''}';
        }
      }
      return '';
    }

    return {
      'active': active,
      'turn_user': turn,
      'turn_name': nameOf(turn),
      'last_user': '${lastPick?['name_last'] ?? ''}',
      'last_team': '${lastPick?['team_name'] ?? ''}',
      'last_player': '${lastPick?['player_name'] ?? ''}',
      'last_title': '${lastPick?['title'] ?? ''}',
    };
  }

