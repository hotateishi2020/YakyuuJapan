          OR replace(replace(COALESCE(nickname, ''), '　', ''), ' ', '') LIKE \$2 ESCAPE '\\'
          OR replace(replace(COALESCE(name_handle, ''), '　', ''), ' ', '') LIKE \$2 ESCAPE '\\'
        )
      ORDER BY name_last, id
      LIMIT 8
      ''',
      parameters: [actorId, like],
    );
    return [
      for (final row in rows)
        if ('${row.toColumnMap()['name'] ?? ''}'.trim().isNotEmpty)
          {
            'id': _asInt(row.toColumnMap()['id']),
            'name': '${row.toColumnMap()['name']}'.trim(),
            'color': '${row.toColumnMap()['code_color'] ?? ''}',
          },
    ];
  }

  static Future<Map<String, dynamic>?> createGroup(
    Connection conn, {
    required String name,
    required int userId,
    required List<int> inviteeIds,
  }) async {
    await ensureSchema(conn);
    final trimmed = name.trim();
    if (userId <= 0) return {'error': 'ログインしてください'};
    if (trimmed.isEmpty || trimmed.length > 100) {
      return {'error': 'グループ名を入力してください'};
    }
    await conn.execute('BEGIN');
    try {
      final inserted = await conn.execute(
        '''
        INSERT INTO t_predict_group (txt_name, crtby, updby)
        VALUES (\$1, \$2, \$2)
        RETURNING id
        ''',
        parameters: [trimmed, userId],
      );
      final groupId = _asInt(inserted.first.toColumnMap()['id']);
      await conn.execute(
        '''
        INSERT INTO t_predict_group_user (id_predict_group, id_user, crtby, updby)
        VALUES (\$1, \$2, \$2, \$2)
        ''',
        parameters: [groupId, userId],
      );
      for (final invitee in inviteeIds.toSet()) {
        if (invitee <= 0 || invitee == userId) continue;
        await conn.execute(
          '''
          INSERT INTO t_predict_invite (id_predict_group, id_user, id_from, crtby, updby)
          SELECT \$1, \$2, \$3, \$3, \$3
          WHERE EXISTS (
            SELECT 1 FROM m_user WHERE id = \$2 AND COALESCE(flg_delete, FALSE) = FALSE
          )
            AND NOT EXISTS (
              SELECT 1 FROM t_predict_group_user
              WHERE id_predict_group = \$1 AND id_user = \$2 AND COALESCE(flg_delete, FALSE) = FALSE
            )
            AND NOT EXISTS (
              SELECT 1 FROM t_predict_invite
              WHERE id_predict_group = \$1 AND id_user = \$2
                AND COALESCE(flg_delete, FALSE) = FALSE AND flg_accept IS NULL
            )
          ''',
          parameters: [groupId, invitee, userId],
        );
      }
      await conn.execute('COMMIT');
      return {'id': groupId, 'txt_name': trimmed};
    } catch (e) {
      try {
        await conn.execute('ROLLBACK');
      } catch (_) {}
      rethrow;
    }
  }

  static Future<List<Map<String, dynamic>>> listInvites(Connection conn, {required int userId}) async {
    if (userId <= 0) return [];
    final rows = await conn.execute(
      '''
      SELECT i.id, i.id_predict_group, g.txt_name, mu.name_last AS from_name
      FROM t_predict_invite i
      JOIN t_predict_group g ON g.id = i.id_predict_group AND COALESCE(g.flg_delete, FALSE) = FALSE
      LEFT JOIN m_user mu ON mu.id = i.id_from
      WHERE i.id_user = \$1
        AND i.flg_accept IS NULL
        AND COALESCE(i.flg_delete, FALSE) = FALSE
      ORDER BY i.id DESC
      ''',
      parameters: [userId],
    );
    return [
      for (final row in rows)
        {
          'id': _asInt(row.toColumnMap()['id']),
          'id_predict_group': _asInt(row.toColumnMap()['id_predict_group']),
          'txt_name': '${row.toColumnMap()['txt_name'] ?? ''}',
          'from_name': '${row.toColumnMap()['from_name'] ?? ''}',
        },
    ];
  }

  static Future<Map<String, dynamic>?> answerInvite(
    Connection conn, {
    required int inviteId,
    required int userId,
    required bool accept,
  }) async {
    await ensureSchema(conn);
    final rows = await conn.execute(
      '''
      SELECT id, id_predict_group
      FROM t_predict_invite
      WHERE id = \$1 AND id_user = \$2 AND flg_accept IS NULL AND COALESCE(flg_delete, FALSE) = FALSE
      ''',
      parameters: [inviteId, userId],
    );
    if (rows.isEmpty) return {'error': '招待が見つかりません'};
    final groupId = _asInt(rows.first.toColumnMap()['id_predict_group']);
    await conn.execute('BEGIN');
    try {
      await conn.execute(
        '''
        UPDATE t_predict_invite
        SET flg_accept = \$3, updat = NOW(), updby = \$2
        WHERE id = \$1 AND id_user = \$2
        ''',
        parameters: [inviteId, userId, accept],
      );
      if (accept) {
        await conn.execute(
          '''
          INSERT INTO t_predict_group_user (id_predict_group, id_user, crtby, updby)
          SELECT \$1, \$2, \$2, \$2
          WHERE NOT EXISTS (
            SELECT 1 FROM t_predict_group_user
            WHERE id_predict_group = \$1 AND id_user = \$2 AND COALESCE(flg_delete, FALSE) = FALSE
          )
          ''',
          parameters: [groupId, userId],
        );
      }
      await conn.execute('COMMIT');
      return {'ok': true, 'accepted': accept};
    } catch (e) {
      try {
        await conn.execute('ROLLBACK');
      } catch (_) {}
      rethrow;
    }
  }

  static Future<Map<String, dynamic>?> requestDelete(
    Connection conn, {
    required int groupId,
    required int userId,
  }) async {
    await ensureSchema(conn);
    final members = await _memberIds(conn, groupId);
    if (!members.contains(userId)) return {'error': '参加ユーザーだけが削除できます'};
    await conn.execute('BEGIN');
    try {
      await conn.execute(
        '''
        INSERT INTO t_predict_group_delete_vote (id_predict_group, id_user, crtby)
        VALUES (\$1, \$2, \$2)
        ON CONFLICT (id_predict_group, id_user) WHERE flg_delete = FALSE DO NOTHING
        ''',
        parameters: [groupId, userId],
      );
      final votes = await conn.execute(
        '''
        SELECT id_user FROM t_predict_group_delete_vote
        WHERE id_predict_group = \$1 AND COALESCE(flg_delete, FALSE) = FALSE
        ''',
        parameters: [groupId],
      );
      final agreed = {for (final row in votes) _asInt(row.toColumnMap()['id_user'])}.intersection(members);
      final applied = members.isNotEmpty && agreed.length >= members.length;
      if (applied) {
        await conn.execute(
          '''
          UPDATE t_predict_group
          SET flg_delete = TRUE, updat = NOW(), updby = \$2
          WHERE id = \$1
          ''',
          parameters: [groupId, userId],
        );
        await conn.execute(
          '''
          UPDATE t_predict_setting
          SET flg_delete = TRUE, updat = NOW(), updby = \$2
          WHERE id_predict_group = \$1 AND COALESCE(flg_delete, FALSE) = FALSE
          ''',
          parameters: [groupId, userId],
        );
        await conn.execute(
          '''
          UPDATE t_predict_invite
          SET flg_delete = TRUE, updat = NOW(), updby = \$2
          WHERE id_predict_group = \$1 AND flg_accept IS NULL AND COALESCE(flg_delete, FALSE) = FALSE
          ''',
          parameters: [groupId, userId],
        );
      }
      await conn.execute('COMMIT');
      return {'applied': applied, 'agreed': agreed.length, 'members': members.length};
    } catch (e) {
      try {
        await conn.execute('ROLLBACK');
      } catch (_) {}
      rethrow;
    }
  }

  static Future<Map<String, dynamic>?> createYear(
    Connection conn, {
    required int groupId,
    required int year,
    required int userId,
  }) async {
    await ensureSchema(conn);
    if (year < 1990 || year > 2100) return {'error': '年度が不正です'};
    final members = await _memberIds(conn, groupId);
    if (!members.contains(userId)) return {'error': '参加ユーザーだけが年度を追加できます'};
    final exists = await conn.execute(
      '''
      SELECT id FROM t_predict_setting
      WHERE id_predict_group = \$1 AND int_year = \$2 AND COALESCE(flg_delete, FALSE) = FALSE
      ''',
      parameters: [groupId, year],
    );
    if (exists.isNotEmpty) return {'error': '$year年の予想はすでにあります'};
    await conn.execute('BEGIN');
    try {
      final inserted = await conn.execute(
        '''
        INSERT INTO t_predict_setting (id_predict_group, int_year, crtby, updby)
        VALUES (\$1, \$2, \$3, \$3)
        RETURNING id
        ''',
        parameters: [groupId, year, userId],
      );
      final settingId = _asInt(inserted.first.toColumnMap()['id']);
      await conn.execute(
        '''
        INSERT INTO t_predict_setting_details (id_predict_setting, id_stats, txt_title, crtby, updby)
        SELECT \$1, d.id_stats, d.txt_title, \$2, \$2
        FROM t_predict_setting_details d
        JOIN t_predict_setting s ON s.id = d.id_predict_setting
        WHERE s.id_predict_group = \$3
          AND s.id <> \$1
          AND COALESCE(s.flg_delete, FALSE) = FALSE
          AND COALESCE(d.flg_delete, FALSE) = FALSE
          AND s.int_year = (
            SELECT MAX(int_year) FROM t_predict_setting
            WHERE id_predict_group = \$3 AND id <> \$1 AND COALESCE(flg_delete, FALSE) = FALSE
          )
        ''',
        parameters: [settingId, userId, groupId],
      );
      await conn.execute('COMMIT');
      return {'id_setting': settingId, 'int_year': year};
    } catch (e) {
      try {
        await conn.execute('ROLLBACK');
      } catch (_) {}
      rethrow;
    }
  }

