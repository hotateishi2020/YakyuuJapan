  static Future<Map<String, dynamic>?> updateSetting(
    Connection conn, {
    required int id,
    required String dateLimitTeam,
    required String dateLimitPlayer,
    required String codeSelect,
    required int samePlayerLimit,
    required String codePoint,
    required int updby,
    List<Map<String, dynamic>>? titles,
    List<Map<String, dynamic>>? picks,
    List<Map<String, dynamic>>? ranks,
    List<Map<String, dynamic>>? champions,
  }) async {
    await ensureSchema(conn);
    if (!selectCodes.contains(codeSelect) || !pointCodes.contains(codePoint)) {
      return null;
    }
    if (!_validDate(dateLimitTeam) || !_validDate(dateLimitPlayer)) {
      return {'error': '期限の日付が不正です'};
    }
    final limit = samePlayerLimit < 1 ? 1 : (samePlayerLimit > 99 ? 99 : samePlayerLimit);
    final current = await _settingRow(conn, id);
    if (current == null) return null;
    final members = await _memberIds(conn, _asInt(current['id_predict_group']));
    if (!members.contains(updby)) return {'error': '参加ユーザーだけが修正できます'};
    if (picks != null && _deadlinePassed(current['date_limit_player'])) {
      return {'error': '個人成績予想の期限を過ぎているため変更できません'};
    }
    if (ranks != null && _deadlinePassed(current['date_limit_team'])) {
      return {'error': 'チーム順位の予想期限を過ぎているため変更できません'};
    }
    final preparedTitles = titles == null ? null : await _prepareTitles(conn, titles);
    if (preparedTitles != null && preparedTitles['error'] != null) {
      return {'error': preparedTitles['error']};
    }
    final preparedPicks = picks == null ? null : await _preparePicks(conn, id, picks, updby);
    if (preparedPicks != null && preparedPicks['error'] != null) {
      return {'error': preparedPicks['error']};
    }
    if (preparedPicks != null && '${current['code_select'] ?? ''}' == 'WAIVER') {
      final blocked = await _waiverPickError(
        conn,
        settingId: id,
        year: _asInt(current['int_year']),
        actorId: updby,
        members: members,
        nextPicks: preparedPicks['picks'] as List<Map<String, dynamic>>,
      );
      if (blocked != null) return {'error': blocked};
    }
    final preparedRanks = ranks == null ? null : await _prepareRanks(conn, ranks, champions ?? const [], updby);
    if (preparedRanks != null && preparedRanks['error'] != null) {
      return {'error': preparedRanks['error']};
    }
    final rulesDiffer = _dateText(current['date_limit_team']) != dateLimitTeam || _dateText(current['date_limit_player']) != dateLimitPlayer || '${current['code_select'] ?? ''}' != codeSelect || (_asInt(current['int_same_player_limit']) == 0 ? 1 : _asInt(current['int_same_player_limit'])) != limit || '${current['code_point'] ?? ''}' != codePoint;
    await conn.execute('BEGIN');
    try {
      final year = _asInt(current['int_year']);
      if (preparedTitles != null) {
        await _replaceTitles(conn, id, updby, preparedTitles['titles'] as List<Map<String, dynamic>>);
      }
      if (preparedPicks != null) {
        await _replacePlayers(
          conn,
          id: id,
          year: year,
          userId: updby,
          picks: preparedPicks['picks'] as List<Map<String, dynamic>>,
        );
      }
      if (preparedRanks != null) {
        await _replaceTeams(
          conn,
          id: id,
          year: year,
          userId: updby,
          ranks: preparedRanks['ranks'] as List<Map<String, dynamic>>,
        );
      }
      var applied = false;
      if (rulesDiffer) {
        applied = await _proposeRules(
          conn,
          settingId: id,
          members: members,
          updby: updby,
          dateLimitTeam: dateLimitTeam,
          dateLimitPlayer: dateLimitPlayer,
          codeSelect: codeSelect,
          samePlayerLimit: limit,
          codePoint: codePoint,
        );
      }
      await conn.execute('COMMIT');
      return {
        'id_setting': id,
        'date_limit_team': _dateText(current['date_limit_team']),
        'date_limit_player': _dateText(current['date_limit_player']),
        'code_select': '${current['code_select'] ?? codeSelect}',
        'int_same_player_limit': _asInt(current['int_same_player_limit']),
        'code_point': '${current['code_point'] ?? codePoint}',
        'proposal_pending': rulesDiffer && !applied,
        'proposal_applied': applied,
      };
    } catch (e) {
      try {
        await conn.execute('ROLLBACK');
      } catch (_) {}
      rethrow;
    }
  }

