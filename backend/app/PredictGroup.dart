  static bool _validDate(String value) => value.isEmpty || RegExp(r'^\d{4}-\d{2}-\d{2}$').hasMatch(value);

  static String _dateText(dynamic value) {
    if (value == null) return '';
    final text = '$value'.trim();
    if (text.length >= 10 && RegExp(r'^\d{4}-\d{2}-\d{2}').hasMatch(text.substring(0, 10))) {
      return text.substring(0, 10);
    }
    return '';
  }

  static bool _deadlinePassed(dynamic value) {
    final day = _dateText(value);
    if (day.isEmpty) return false;
    final now = DateTime.now().toUtc().add(const Duration(hours: 9));
    final today = '${now.year.toString().padLeft(4, '0')}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
    return today.compareTo(day) > 0;
  }

