# coding: utf-8
"""Refresh source-backed FA acquisition events; never infer acquisition from debut year.
Run from repository root: python3 backend/tool_refresh_fa_rights.py
"""
import json, re, unicodedata, subprocess
from html.parser import HTMLParser
from urllib.request import urlopen
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

class Node:
 def __init__(self,tag='',attrs=()): self.tag=tag;self.attrs=dict(attrs);self.children=[];self.parts=[]
 def text(self): return ''.join(p.text() if isinstance(p,Node) else p for p in self.parts)
 def all(self,tag=None,cls=None):
  return [n for c in self.children for n in [c]+c.all() if (tag is None or n.tag==tag) and (cls is None or cls in n.attrs.get('class','').split())]
class Tree(HTMLParser):
 def __init__(self,s):
  super().__init__();self.root=Node();self.stack=[self.root];self.feed(s)
 def handle_starttag(self,t,a):
  n=Node(t,a);self.stack[-1].children.append(n);self.stack[-1].parts.append(n)
  if t not in ['br','img','meta','link','input','hr','source','wbr']:self.stack.append(n)
 def handle_endtag(self,t):
  for i in range(len(self.stack)-1,0,-1):
   if self.stack[i].tag==t:self.stack=self.stack[:i];break
 def handle_data(self,s):self.stack[-1].parts.append(s)
def fetch(url):
 data = subprocess.check_output(['curl', '--fail', '--silent', '--show-error', '--location', '--max-time', '30', '-A', 'Mozilla/5.0', url])
 return Tree(data.decode('utf-8')).root
def normalized(s):return re.sub(r'\s+','',unicodedata.normalize('NFKC',s))
def official(year):
 url=f'https://npb.jp/announcement/{year}/fa_qualified.html';doc=fetch(url);out=[]
 for row in doc.all('tr'):
  if not any(c.tag=='th' and 'fateam' in c.attrs.get('class','') for c in row.children):continue
  cells=[c for c in row.children if c.tag=='td']
  if len(cells) not in (2,4):raise ValueError(f'Unexpected columns: {year}')
  for i,kind in [(0,'domestic'),(2 if len(cells)==4 else 1,'international')]:
   links=cells[i].all('a') if len(cells)==4 else [a for td in cells[i].all('td') if any('※' in n.text() or '＃' in n.text() for n in td.all(cls='fa_mark')) for a in td.all('a')]
   for a in links:
    match=re.search(r'/players/(\d+)\.html',a.attrs.get('href',''))
    if match:out.append(dict(player_key='npb:'+match[1],name=normalized(a.text()),year=year,type=kind,source_url=url,projected=False,detail='NPB公式公示の今季取得者。再取得を含みます。'))
 return out

def main():
 events=[]
 with ThreadPoolExecutor(max_workers=3) as pool:
  for year,rows in zip(range(2008,2026),pool.map(official,range(2008,2026))):
   events.extend(rows);print(year,len(rows),flush=True)
 current=fetch('https://facounter.net/fa2026.html')
 for article in current.all('article', 'pl'):
  if not any('国内FA 新規取得' in n.text() for n in article.all(cls='p-done')):continue
  name=article.all('h3')[0].text()
  notes=article.all(cls='note')
  events.append(dict(name=normalized(name),year=2026,type='domestic',source_url='https://facounter.net/fa2026.html#'+article.attrs['id'],projected=False,detail=notes[0].text() if notes else '取得済みとして掲載。'))
 future=fetch('https://facounter.net/future.html')
 for pane in future.all(cls='pane'):
  year=int(pane.attrs['data-year'])
  if year<=2026:continue
  for li in pane.all('li'):
   links=li.all('a', 'to-player')
   if not links:continue
   events.append(dict(name=normalized(links[0].text()),year=year,type='domestic',source_url='https://facounter.net/future.html',projected=True,detail='年間145日一軍登録を仮定した最短の試算。故障・登録抹消・特例措置等で前後します。'))
 events.append(dict(name='外崎修汰',year=2026,type='international',projected=False,source_url='https://www.nikkansports.com/baseball/news/202609300000729.html',detail='2026年9月30日、故障者特例を含め海外FAの取得条件を満たしたとの報道。'))
 # Dart const dataset avoids network calls when opening the contract tab.
 out=Path('lib/data/npb_fa_rights.dart');out.parent.mkdir(exist_ok=True)
 out.write_text('// Generated by backend/tool_refresh_fa_rights.py. Checked 2026-10-15.\nconst npbFaRights = <Map<String, dynamic>>'+json.dumps(events,ensure_ascii=False,indent=2)+';\n')
 print('events',len(events))
if __name__=='__main__':main()
